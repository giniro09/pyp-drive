import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../docs/index.html',import.meta.url),'utf8');
const start=html.indexOf('  function drawBranchReward(');
const end=html.indexOf('\n  if (settings.minimalUI)',start);
const c=vm.createContext({Math,decision:{},activeLeadTracking:null,capturedLeadKeys:new Set(),branchMults:{left:1.4},LABEL_JA:{left:'左折'},getLeadContinuationBranchId:()=> 'left'});
vm.runInContext(html.slice(start,end),c);
const b={id:'left',label:'left',angleDeg:-90,selected:true,lead:{id:'one',type:'supply',status:'available',targetDistanceM:280}};
let rendered=c.drawBranchReward(b,{text:'×1.4'});
assert.match(rendered,/assets\/loot\/supply.png/);
assert.match(rendered,/>280m</);
assert.match(rendered,/気配 · ×1.4/);
c.capturedLeadKeys.add('one');
assert.doesNotMatch(c.drawBranchReward(b,{text:'×1.4'}),/<image/);
c.activeLeadTracking={type:'parts',targetDistanceM:420,matchedDistanceM:125};
rendered=c.drawBranchReward(b,{text:'追跡ルート'});
assert.match(rendered,/assets\/loot\/parts.png/);
assert.match(rendered,/>295m</);
assert.match(rendered,/追跡中/);
for(const type of ['supply','parts']) assert.ok(existsSync(new URL(`../docs/assets/loot/${type}.png`,import.meta.url)));
console.log('PASS: actual lead artwork and distance, collected lead hidden, active trace remaining distance, local assets');
