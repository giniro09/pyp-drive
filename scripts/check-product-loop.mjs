import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../docs/playtest.html',import.meta.url),'utf8');
const ui=html.match(/<script type="module">([\s\S]*?)<\/script>/)[1].replace(/^import.*$/m,'');
new vm.Script(ui);
import{initial,start,offers,choose,settle,build,capacity}from '../docs/playtest-model.js';
const scanner=initial();start(scanner);
assert.equal(offers(scanner)[2].hidden,true);
choose(scanner,0);choose(scanner,1);choose(scanner,1);
assert.equal(scanner.bag.length,5);
assert.equal(settle(scanner,[0,1,2,3]),false,'Must choose within carry capacity');
assert.equal(settle(scanner,[0,1,3]),true);
assert.ok(build(scanner,'scanner'),'First expedition can complete scanner without roulette');
assert.equal(build(scanner,'scanner'),false,'Cannot double build');
start(scanner);assert.equal(offers(scanner)[2].hidden,false,'Equipment changes next decision information');
const cargo=initial();cargo.goal='cargo';start(cargo);
choose(cargo,0);choose(cargo,0);choose(cargo,1);settle(cargo,[0,1,2]);
assert.ok(build(cargo,'cargo'));assert.equal(capacity(cargo),5);
const replay=initial();start(replay);choose(replay,0);settle(replay,[0]);start(replay);settle(replay,[]);start(replay);
assert.equal(offers(replay)[0].count,0,'Previously collected location does not refill');
const debt=initial();debt.money=0;assert.ok(start(debt));assert.equal(debt.money,-5);
const rng=initial();start(rng);choose(rng,0,true);assert.equal(rng.money,26,'Roulette salvage minus route cost');
console.log('PASS: first-trip scanner/cargo builds, second-trip reveal/capacity effects, carry selection, repeat prevention, soft debt, roulette tradeoff');
